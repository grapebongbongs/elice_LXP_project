#!/usr/bin/env bash
# Generate experiment metadata from the committed candidate, then invoke run_experiment.sh.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
RUNNER="$SCRIPT_DIR/run_experiment.sh"

usage() {
  cat <<'EOF'
Usage: bash baseline/scripts/evaluate_current_candidate.sh [options forwarded to run_experiment.sh]

Metadata generated by default:
  id          KST timestamp plus current short commit hash
  hypothesis  current commit subject
  scope       changed-path inference (tutor, guard, or common)

Overrides: --id <value>, --hypothesis <text>, --scope <tutor|guard|common>
All other options, such as --champion-ref and --no-publish, are forwarded.
EOF
}

EXPERIMENT_ID=""
HYPOTHESIS=""
SCOPE=""
FORWARD=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --id) EXPERIMENT_ID="$2"; shift 2 ;;
    --hypothesis) HYPOTHESIS="$2"; shift 2 ;;
    --scope) SCOPE="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) FORWARD+=("$1"); shift ;;
  esac
done

cd "$ROOT_DIR"
[[ -z "$(git status --porcelain)" ]] || { echo "Candidate checkout must be clean" >&2; exit 2; }
[[ -n "$(git branch --show-current)" ]] || { echo "Run from a named candidate branch" >&2; exit 2; }

if [[ -z "$EXPERIMENT_ID" ]]; then
  EXPERIMENT_ID="$(TZ=Asia/Seoul date +%Y%m%d-%H%M%S)-$(git rev-parse --short HEAD)"
fi
if [[ -z "$HYPOTHESIS" ]]; then
  HYPOTHESIS="$(git log -1 --format=%s)"
fi
if [[ -z "$SCOPE" ]]; then
  TUTOR_CHANGED=0
  GUARD_CHANGED=0
  OTHER_CHANGED=0
  while IFS= read -r path; do
    [[ -z "$path" ]] && continue
    case "$path" in
      baseline/app/tutor/*) TUTOR_CHANGED=1 ;;
      baseline/app/guard/*) GUARD_CHANGED=1 ;;
      *) OTHER_CHANGED=1 ;;
    esac
  done < <(git diff --name-only origin/main...HEAD)
  if [[ "$TUTOR_CHANGED" == "1" && "$GUARD_CHANGED" == "0" && "$OTHER_CHANGED" == "0" ]]; then
    SCOPE="tutor"
  elif [[ "$GUARD_CHANGED" == "1" && "$TUTOR_CHANGED" == "0" && "$OTHER_CHANGED" == "0" ]]; then
    SCOPE="guard"
  else
    SCOPE="common"
  fi
fi

echo "[experiment] generated id: $EXPERIMENT_ID"
echo "[experiment] generated scope: $SCOPE"
echo "[experiment] generated hypothesis: $HYPOTHESIS"
exec bash "$RUNNER" --id "$EXPERIMENT_ID" --scope "$SCOPE" --hypothesis "$HYPOTHESIS" "${FORWARD[@]}"
